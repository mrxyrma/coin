/**
 * Конфигурация полёта монеты — единственное место, где живут цифры анимации.
 *
 * Позиции НЕ задаются здесь: их даёт CSS через `.coin-anchor` в каждой секции.
 * Здесь только характер движения: наклон, обороты и вынос дуги вбок.
 *
 * Порядок элементов = порядок пролёта. Он же должен совпадать с порядком
 * якорей в документе.
 */

export type Waypoint = {
  /** Совпадает с data-coin-anchor в разметке */
  id: string
  /**
   * Наклон вокруг горизонтальной оси, радианы. 0 — монета «лицом» к зрителю.
   */
  rotX: number
  /**
   * Сколько полуоборотов монета доворачивает по пути К этой точке.
   * Нечётное число = меняется видимая сторона (аверс ↔ реверс).
   */
  halfTurnsIn: number
  /**
   * Вынос дуги вбок на сегменте, ВЫХОДЯЩЕМ из этой точки.
   * Доля ширины вьюпорта, знак = сторона. Снято со стрелок макета;
   * значения приблизительные — макет прототипный, это ручка для тюнинга.
   */
  bulgeOut: number
}

/**
 * Финальный ракурс укладки в ложемент.
 * В макете монета в футляре — эллипс 206×144, значит cos θ = 144/206,
 * θ ≈ 45.6°. Монета не лежит плашмя, а стоит в углублении под наклоном.
 */
export const CASE_TILT = -Math.acos(144 / 206) // ≈ −0.796 рад

/**
 * Наклон самого футляра на странице.
 *
 * Выводится из CASE_TILT, а не подбирается на глаз. Монета — плоский диск
 * с нормалью +Z, футляр стоит дном в плоскости XZ, то есть его нормаль +Y.
 * Разница между осями ровно π/2, поэтому футляр доворачивается на столько
 * же больше: тогда дно ложемента параллельно плоскости монеты и она
 * ложится в углубление, а не протыкает его под чужим углом.
 */
export const CASE_VIEW_TILT = Math.PI / 2 + CASE_TILT

/** Доворот футляра вокруг вертикали — ракурс 3/4, как на референс-рендере */
export const CASE_VIEW_TURN = 0.3

